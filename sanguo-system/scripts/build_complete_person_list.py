def main():
    # 解析名字列表
    names = []
    for line in RAW_NAMES.split('\n'):
        line = line.strip()
        if not line:
            continue
        parts = line.split()
        for p in parts:
            p = p.strip()
            if len(p) >= 2:
                names.append(p)
    
    # 去重
    seen = set()
    unique_names = []
    for n in names:
        if n not in seen:
            seen.add(n)
            unique_names.append(n)
    
    print(f'提取人物数量: {len(unique_names)}')
    
    # 读取原文
    print('读取原文...')
    text = read_text()
    chapters = split_chapters(text)
    print(f'章回数: {len(chapters)}')
    
    # 统计出场次数
    print('统计出场次数（含别名）...')
    stats = []
    for i, name in enumerate(unique_names):
        aliases = get_aliases(name)
        total = 0
        first_ch = None
        related_chs = []
        
        for ch in chapters:
            ch_count = 0
            for alias in aliases:
                ch_count += ch['content'].count(alias)
            if ch_count > 0:
                total += ch_count
                related_chs.append(ch['number'])
                if first_ch is None:
                    first_ch = ch['number']
        
        if total > 0:
            stats.append({
                'name': name,
                'aliases': aliases,
                'count': total,
                'firstChapter': first_ch,
                'relatedChapters': related_chs
            })
        
        if (i + 1) % 100 == 0:
            print(f'  已处理 {i+1}/{len(unique_names)}...')
    
    # 按出场次数排序
    stats.sort(key=lambda x: -x['count'])
    
    # 保存结果
    with open(OUT, 'w', encoding='utf-8') as f:
        json.dump(stats, f, ensure_ascii=False, indent=2)
    
    print(f'\n已保存 {len(stats)} 个有出场记录的人物 -> {OUT}')
    print()
    print('前50名:')
    for i, s in enumerate(stats[:50]):
        print(f"{i+1}. {s['name']}: {s['count']}次 (首出场第{s['firstChapter']}回)")
    print()
    print(f'总人数: {len(stats)}')

if __name__ == '__main__':
    main()
